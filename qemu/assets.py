"""Release assets for the QEMU build: the zip, its checksum, and the files that go with it.

    assets.py zip    --stage <dir> --out <zip>
    assets.py sha256 <file>
    assets.py qapi   --source <extracted qemu source> --out <zip>
    assets.py stanza --zip <zip> --tag <tag> --repo <owner/repo>
    assets.py notes  --tag <tag> --repo <owner/repo>
    assets.py check-manifest <qemu-manifest.toml>
"""

import argparse
import hashlib
import re
import shutil
import sys
import tomllib
import urllib.error
import urllib.request
import zipfile
from pathlib import Path

# What devvm reads out of the zip (the Interfaces of the unit plan), plus the files that make it redistributable.
REQUIRED = (
    "bin/qemu-system-x86_64.exe",
    "bin/qemu-system-aarch64.exe",
    "bin/qemu-img.exe",
    "share/edk2-x86_64-code.fd",
    "share/edk2-i386-vars.fd",
    "share/edk2-aarch64-code.fd",
    "share/edk2-arm-vars.fd",
    "licenses/qemu/COPYING",
    "BUILD-INFO.txt",
    "THIRD-PARTY.txt",
    "SOURCE.txt",
)

TAG = re.compile(r"^qemu-(\d+\.\d+\.\d+)-(\d+)$")
VERIFY = "gh attestation verify <file> -R {repo} --signer-workflow {repo}/.github/workflows/qemu.yaml"


def sha256_of(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as f:
        for block in iter(lambda: f.read(1 << 20), b""):
            digest.update(block)
    return digest.hexdigest()


def release_url(repo: str, tag: str, asset: str) -> str:
    return f"https://github.com/{repo}/releases/download/{tag}/{asset}"


def zip_triple(zip_path: Path, tag: str) -> str:
    name = zip_path.name
    if not (name.startswith(f"{tag}-") and name.endswith(".zip")):
        raise SystemExit(f"FAIL: {name} is not named {tag}-<triple>.zip")
    return name.removeprefix(f"{tag}-").removesuffix(".zip")


def tag_version(tag: str) -> str:
    match = TAG.match(tag)
    if match is None:
        raise SystemExit(f"FAIL: {tag} is not qemu-<version>-<revision>")
    return match.group(1)


def add_file(archive: zipfile.ZipFile, name: str, path: Path) -> None:
    # A fixed timestamp makes the same input zip to the same bytes.
    info = zipfile.ZipInfo(name, date_time=(1980, 1, 1, 0, 0, 0))
    info.compress_type = zipfile.ZIP_DEFLATED
    info.external_attr = 0o644 << 16
    with path.open("rb") as src, archive.open(info, "w") as dst:
        shutil.copyfileobj(src, dst, 1 << 20)


def cmd_zip(args: argparse.Namespace) -> int:
    missing = [name for name in REQUIRED if not (args.stage / name).is_file()]
    if missing:
        print(f"FAIL: the stage lacks {', '.join(missing)}")
        return 1

    files = sorted(p for p in args.stage.rglob("*") if p.is_file())
    args.out.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(args.out, "w", zipfile.ZIP_DEFLATED, compresslevel=9) as archive:
        for path in files:
            add_file(archive, path.relative_to(args.stage).as_posix(), path)
    print(f"{args.out} {args.out.stat().st_size} bytes, {len(files)} files, sha256 {sha256_of(args.out)}")
    return 0


def cmd_sha256(args: argparse.Namespace) -> int:
    digest = sha256_of(args.file)
    target = args.file.with_name(args.file.name + ".sha256")
    target.write_text(f"{digest} *{args.file.name}\n", newline="\n")
    print(digest)
    return 0


def cmd_qapi(args: argparse.Namespace) -> int:
    schemas = sorted((args.source / "qapi").glob("*.json"))
    if not any(p.name == "qapi-schema.json" for p in schemas):
        print(f"FAIL: no qapi/qapi-schema.json under {args.source}")
        return 1
    args.out.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(args.out, "w", zipfile.ZIP_DEFLATED, compresslevel=9) as archive:
        for path in schemas:
            add_file(archive, f"qapi/{path.name}", path)
        add_file(archive, "COPYING", args.source / "COPYING")
    print(f"{args.out}: {len(schemas)} schema files")
    return 0


def cmd_stanza(args: argparse.Namespace) -> int:
    triple = zip_triple(args.zip, args.tag)
    print("# Generated by .github/workflows/qemu.yaml from the published release; do not edit.")
    print(f"[targets.{triple}]")
    print(f'qemu_version = "{tag_version(args.tag)}"')
    print(f'url = "{release_url(args.repo, args.tag, args.zip.name)}"')
    print(f'sha256 = "{sha256_of(args.zip)}"')
    return 0


def cmd_notes(args: argparse.Namespace) -> int:
    version = tag_version(args.tag)
    verify = VERIFY.format(repo=args.repo)
    print(f"""QEMU {version} for devvm, built from the upstream release tarball in CI.

**Assets**

- `{args.tag}-<target triple>.zip` and `.sha256`: the build (`x86_64-pc-windows-msvc`). Self-contained: QEMU, every
  non-system DLL, the edk2 UEFI firmware, licences, `BUILD-INFO.txt`, `THIRD-PARTY.txt`, `SOURCE.txt`.
- `qemu-{version}.tar.xz` and `.sig`: the exact upstream source the build was made from (GPL-2.0-or-later).
- `{args.tag}-build-scripts.tar.gz`: the build scripts and workflow at the build commit.
- `{args.tag}-qapi.zip`: QEMU's QAPI schema (`qapi/*.json`).
- `*.src.tar.zst`: the source archives of the bundled LGPL/GPL MSYS2 libraries, exactly the versions in the zip.
- `qemu-manifest.toml`: the devvm manifest entry for this build.

**Verify**

```
{verify}
```

**Firmware.** `share/edk2-*.fd` are the prebuilt edk2 binaries that ship inside the QEMU tarball, not rebuilt
here; their source is under `roms/edk2` in the attached tarball.

**Source offer.** The complete corresponding source of everything in the zip is attached to this release (see
`SOURCE.txt` in the zip). The bundled libraries are separate DLLs that can be replaced by a modified build of the
attached source (LGPL section 6). Should an asset become unavailable, request the source in the issue tracker of
{args.repo}; it will be provided for three years from the release date.""")
    return 0


def cmd_check_manifest(args: argparse.Namespace) -> int:
    if not args.manifest.exists():
        print(f"notice: {args.manifest} does not exist yet; nothing to check")
        return 0
    targets = tomllib.loads(args.manifest.read_text(encoding="utf-8")).get("targets", {})
    if not targets:
        print(f"FAIL: {args.manifest} has no [targets.*] table")
        return 1
    failed = False
    for triple, entry in targets.items():
        digest = hashlib.sha256()
        try:
            with urllib.request.urlopen(entry["url"]) as response:
                for block in iter(lambda: response.read(1 << 20), b""):
                    digest.update(block)
        except urllib.error.URLError as error:
            print(f"FAIL: {triple}: cannot download {entry['url']}: {error}")
            failed = True
            continue
        if f"/qemu-{entry['qemu_version']}-" not in entry["url"]:
            print(f"FAIL: {triple}: url {entry['url']} does not match qemu_version {entry['qemu_version']}")
            failed = True
        elif digest.hexdigest() != entry["sha256"]:
            print(f"FAIL: {triple}: {entry['url']} has sha256 {digest.hexdigest()}, the manifest says {entry['sha256']}")
            failed = True
        else:
            print(f"ok: {triple}: {entry['url']}")
    return 1 if failed else 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest="command", required=True)

    zip_ = sub.add_parser("zip", help="zip a stage directory")
    zip_.add_argument("--stage", type=Path, required=True)
    zip_.add_argument("--out", type=Path, required=True)
    zip_.set_defaults(func=cmd_zip)

    digest = sub.add_parser("sha256", help="write <file>.sha256 in sha256sum format and print the hash")
    digest.add_argument("file", type=Path)
    digest.set_defaults(func=cmd_sha256)

    qapi = sub.add_parser("qapi", help="zip QEMU's qapi/*.json")
    qapi.add_argument("--source", type=Path, required=True)
    qapi.add_argument("--out", type=Path, required=True)
    qapi.set_defaults(func=cmd_qapi)

    stanza = sub.add_parser("stanza", help="print the qemu-manifest.toml table for a release")
    stanza.add_argument("--zip", type=Path, required=True)
    stanza.add_argument("--tag", required=True)
    stanza.add_argument("--repo", required=True)
    stanza.set_defaults(func=cmd_stanza)

    notes = sub.add_parser("notes", help="print the release notes")
    notes.add_argument("--tag", required=True)
    notes.add_argument("--repo", required=True)
    notes.set_defaults(func=cmd_notes)

    manifest = sub.add_parser("check-manifest", help="download each url in the manifest and compare sha256")
    manifest.add_argument("manifest", type=Path)
    manifest.set_defaults(func=cmd_check_manifest)

    args = parser.parse_args()
    return args.func(args)


if __name__ == "__main__":
    sys.exit(main())
